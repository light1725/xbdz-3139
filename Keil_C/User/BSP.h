/*****************************************************************************************************
 * @file    BSP.h
 * @brief   0010903139 触控板底层板级支持包头文件 (芯片: SC92F8461B)
 * @details 硬件引脚定义与配置:
 *          - DAT (Pin 16 / P0.0): 单线通信发送引脚，强推挽输出，空闲高电平
 *          - L2  (Pin 7  / P1.3): 风速/延时指示灯，低电平点亮，强推挽输出
 *          - L4  (Pin 8  / P1.5): 照明指示灯，低电平点亮，强推挽输出
 *          - K2  (Pin 13 / P2.0): 赛元触控 TK8 (照明按键)
 *          - K4  (Pin 10 / P2.5): 赛元触控 TK13 (风机+延时按键)
 *****************************************************************************************************/
#ifndef _BSP_H_
#define _BSP_H_

#include "sc92f.h"

/*******************************************************************************
 * GPIO 控制宏定义 (X_h: 引脚输出高电平, X_l: 引脚输出低电平)
 *******************************************************************************/
#define P00_h       (P00 = 1)
#define P00_l       (P00 = 0)
#define P13_h       (P13 = 1)
#define P13_l       (P13 = 0)
#define P15_h       (P15 = 1)
#define P15_l       (P15 = 0)
#define P20_h       (P20 = 1)
#define P20_l       (P20 = 0)
#define P25_h       (P25 = 1)
#define P25_l       (P25 = 0)

// 兼容别名
#define P1_3_h      P13_h
#define P1_3_l      P13_l
#define P1_5_h      P15_h
#define P1_5_l      P15_l
#define P0_0_h      P00_h
#define P0_0_l      P00_l

/*******************************************************************************
 * 函数声明
 *******************************************************************************/
void Set_GPIO_Output(uint8_t port, uint8_t pin);
void BSP_Timer0_Init(void);
void BSP_GPIO_Init(void);
void Delay_10us(void);
void Delay_us(uint16_t us);
void Delay_ms(uint16_t ms);

#endif /* _BSP_H_ */